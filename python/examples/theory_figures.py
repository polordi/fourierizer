"""Figures and tables for the theory document (docs/theory).

Every number printed in the document comes from here, computed with the same window code the
engine uses. Writes PDFs and .tex tables to docs/theory/generated/.

    python examples/theory_figures.py
"""

from __future__ import annotations

from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

from fourierizer_ref.windows import make_window

OUT = Path(__file__).resolve().parents[2] / "docs" / "theory" / "generated"
INK, MUTED, SEAM = "#16181A", "#5A6068", "#B7BDC3"

# (key, display name, params, color)
WINS = [
    ("rect", "Rectangular", {}, MUTED),
    ("hann", "Hann", {}, "#B85A00"),
    ("hamming", "Hamming", {}, "#0B7A36"),
    ("blackman_harris", "Blackman-Harris", {}, "#006A9E"),
    ("kaiser", r"Kaiser ($\beta=8$)", {"beta": 8.0}, "#6330B0"),
    ("gauss", r"Gauss ($\sigma=0.4$)", {"sigma": 0.4}, "#C2187A"),
    ("flat_top", "Flat-top", {}, INK),
]

L = 128         # window length for the analysis (results are in bins, so L only sets precision)
OVERSAMPLE = 256


def spectrum_db(w: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """|W(θ)| in dB normalized to 0 dB at DC, on a grid of bins (units of 2π/L)."""
    n = len(w) * OVERSAMPLE
    W = np.abs(np.fft.rfft(w, n))
    bins = np.arange(len(W)) / OVERSAMPLE
    return bins, 20 * np.log10(np.maximum(W / W[0], 1e-12))


def metrics(w: np.ndarray) -> dict[str, float]:
    bins, db = spectrum_db(w)
    # first null: first local minimum of the magnitude after DC
    d = np.diff(db)
    first_null = int(np.argmax((d[:-1] < 0) & (d[1:] >= 0))) + 1
    sidelobe = float(db[first_null:].max())
    enbw = len(w) * np.sum(w ** 2) / np.sum(w) ** 2
    scallop = float(np.interp(0.5, bins, db))
    return {"null": bins[first_null], "sidelobe": sidelobe, "enbw": enbw, "scallop": scallop}


def write_table() -> None:
    rows = []
    for key, name, params, _ in WINS:
        m = metrics(make_window(key, L, **params))
        rows.append(f"{name} & {m['null']:.2f} & {m['sidelobe']:.1f} & {m['enbw']:.2f} & {m['scallop']:.2f} \\\\")
    (OUT / "tabla-ventanas.tex").write_text(
        "% generated by python/examples/theory_figures.py — do not edit\n"
        "\\begin{tabular}{lrrrr}\n\\toprule\n"
        "Ventana & Primer nulo [bins] & Lóbulo lateral máx. [dB] & ENBW [bins] & Festoneo [dB] \\\\\n\\midrule\n"
        + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n", encoding="utf-8")


def style(ax):
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    ax.tick_params(labelsize=8, colors=MUTED)
    ax.grid(color=SEAM, lw=0.5, alpha=0.6)


def fig_windows() -> None:
    fig, (a, b) = plt.subplots(1, 2, figsize=(9, 3.4), constrained_layout=True)
    n = np.arange(L) / L
    for key, name, params, color in WINS:
        w = make_window(key, L, **params)
        a.plot(n, w, color=color, lw=1.4, label=name)
        bins, db = spectrum_db(w)
        b.plot(bins, db, color=color, lw=1.1)
    a.set_xlabel(r"$n/L$", fontsize=9); a.set_ylabel(r"$w[n]$", fontsize=9); a.set_title("Dominio del tiempo", fontsize=10, loc="left")
    b.set_xlim(0, 12); b.set_ylim(-120, 3)
    b.set_xlabel(r"frecuencia relativa [bins $= F_s/N$]", fontsize=9); b.set_ylabel(r"$|W|$ [dB]", fontsize=9)
    b.set_title("Dominio de la frecuencia", fontsize=10, loc="left")
    style(a); style(b)
    a.legend(fontsize=7, frameon=False, ncol=2, loc="lower center")
    fig.savefig(OUT / "ventanas.pdf")
    plt.close(fig)


def fig_leakage() -> None:
    """A 1 kHz tone that falls between two bins, analysed with rect vs Blackman-Harris."""
    sr, N = 48000, 1024
    f0 = 10.5 * sr / N   # exactly half-way between bins 10 and 11
    t = np.arange(N) / sr
    x = np.sin(2 * np.pi * f0 * t) + 10 ** (-60 / 20) * np.sin(2 * np.pi * 24.0 * sr / N * t)  # plus a −60 dB tone
    fig, ax = plt.subplots(figsize=(9, 2.8), constrained_layout=True)
    for key, name, color in (("rect", "Rectangular", MUTED), ("blackman_harris", "Blackman-Harris", "#006A9E")):
        w = make_window(key, N)
        X = np.abs(np.fft.rfft(x * w)); X /= X.max()
        ax.step(np.arange(len(X)), 20 * np.log10(np.maximum(X, 1e-9)), where="mid", color=color, lw=1.2, label=name)
    ax.set_xlim(0, 48); ax.set_ylim(-110, 3)
    ax.axvline(24, color=INK, lw=0.8, ls=":")
    ax.annotate("tono débil (−60 dB)", (24, -62), xytext=(28, -30), fontsize=8, arrowprops={"arrowstyle": "->", "color": INK})
    ax.set_xlabel("bin $k$", fontsize=9); ax.set_ylabel("dB", fontsize=9)
    ax.legend(fontsize=8, frameon=False)
    style(ax)
    fig.savefig(OUT / "fuga.pdf")
    plt.close(fig)


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    write_table()
    fig_windows()
    fig_leakage()
    print((OUT / "tabla-ventanas.tex").read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
